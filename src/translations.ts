function toCamelCase(str: string): string {
  if (!str) return '';
  return str
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
    .replace(/^[A-Z]/, (chr) => chr.toLowerCase());
}

/**
 * Universal translator function that supports keys, camelCase ids, and direct UI strings.
 * Guarantees that all 8 supported Indian languages properly convert headers, navigation,
 * SOS console, dialogs, buttons, permissions, and status text.
 */
export function translate(keyOrText: string, lang: LanguageCode = 'en', defaultText?: string): string {
  if (!keyOrText) return defaultText || '';
  if (lang === 'en') {
    return TRANSLATIONS.en[keyOrText] || defaultText || keyOrText;
  }

  const map = ALL_LANGUAGE_PHRASE_MAPS[lang];
  const langDict = TRANSLATIONS[lang];

  // 1. Direct match in language phrase map
  if (map && map[keyOrText]) {
    return map[keyOrText];
  }

  // 2. Direct match in TRANSLATIONS[lang]
  if (langDict && langDict[keyOrText]) {
    return langDict[keyOrText];
  }

  // 3. Trimmed key match
  const trimmed = keyOrText.trim();
  if (map && map[trimmed]) {
    return map[trimmed];
  }
  if (langDict && langDict[trimmed]) {
    return langDict[trimmed];
  }

  // 4. Case-normalized / camelCase match in TRANSLATIONS[lang]
  const uncap = keyOrText.charAt(0).toLowerCase() + keyOrText.slice(1);
  if (langDict && langDict[uncap]) {
    return langDict[uncap];
  }

  const camelKey = toCamelCase(keyOrText);
  if (langDict && langDict[camelKey]) {
    return langDict[camelKey];
  }

  // 5. If defaultText provided, test defaultText in map and TRANSLATIONS
  if (defaultText) {
    if (map && map[defaultText]) return map[defaultText];
    if (map && map[defaultText.trim()]) return map[defaultText.trim()];
    if (langDict && langDict[defaultText]) return langDict[defaultText];
    const defUncap = defaultText.charAt(0).toLowerCase() + defaultText.slice(1);
    if (langDict && langDict[defUncap]) return langDict[defUncap];
    const defCamel = toCamelCase(defaultText);
    if (langDict && langDict[defCamel]) return langDict[defCamel];
  }

  // 6. Case-insensitive search in map
  if (map) {
    const lowerKey = trimmed.toLowerCase();
    for (const [k, v] of Object.entries(map)) {
      if (k.toLowerCase() === lowerKey) return v;
    }
  }

  // Fallback to English translation or provided default text or key itself
  return TRANSLATIONS.en[keyOrText] || defaultText || keyOrText;
}
